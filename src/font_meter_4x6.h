// Compact meter scale digit font, 4x6 pixels.
#ifndef FONT_METER_4X6_H
#define FONT_METER_4X6_H

#include <stdint.h>

#define FONT_METER_4X6_WIDTH   4U
#define FONT_METER_4X6_HEIGHT  6U

/* Bits 3..0 are pixels from left to right. */
static const uint8_t font_meter_4x6[10][FONT_METER_4X6_HEIGHT] =
{
    { 0x6U, 0x9U, 0x9U, 0x9U, 0x9U, 0x6U }, /* 0 */
    { 0x2U, 0x6U, 0x2U, 0x2U, 0x2U, 0x7U }, /* 1 */
    { 0x6U, 0x9U, 0x1U, 0x2U, 0x4U, 0xFU }, /* 2 */
    { 0xEU, 0x1U, 0x6U, 0x1U, 0x1U, 0xEU }, /* 3 */
    { 0x2U, 0x6U, 0xAU, 0xFU, 0x2U, 0x2U }, /* 4 */
    { 0xFU, 0x8U, 0xEU, 0x1U, 0x9U, 0x6U }, /* 5 */
    { 0x6U, 0x8U, 0xEU, 0x9U, 0x9U, 0x6U }, /* 6 */
    { 0xFU, 0x1U, 0x2U, 0x4U, 0x4U, 0x4U }, /* 7 */
    { 0x6U, 0x9U, 0x6U, 0x9U, 0x9U, 0x6U }, /* 8 */
    { 0x6U, 0x9U, 0x9U, 0x7U, 0x1U, 0x6U }  /* 9 */
};

#endif /* FONT_METER_4X6_H */
