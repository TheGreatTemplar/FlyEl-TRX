const char *ServiceCatalog_TypeName(uint8_t type)
{
    static const char *const names[] = {
        "READ ONLY", "ENUM", "VALUE", "TEXT", "TABLE", "TEST", "ACTION", "MONITOR", "BOOL"
    };
    return (type < sizeof(names) / sizeof(names[0])) ? names[type] : "UNKNOWN";
}
